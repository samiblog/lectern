"""md 문서 스타일 (D103): 문서 방식과 머리글 모양. 머리글은 md 원문에서 바뀌고, 방식을 바꿀 때는 묻고, Claude 는 요청 글까지"""
import os
import sys
import tempfile
import traceback
from pathlib import Path

from playwright.sync_api import sync_playwright

from harness import check, expect, fails, report, serve, stop

base = Path(tempfile.mkdtemp(prefix='lec-mdstyle-'))
proj = base / 'proj'
proj.mkdir()
TEXT = '# 보고서\n\n요약입니다. [시장으로](#시장-현황)\n\n## 개요\n\n글입니다.\n\n### 배경\n\n```md\n## 코드 속 제목\n```\n\n## 시장 현황\n\n- 항목입니다\n'
doc = proj / '보고서.md'
doc.write_text(TEXT, encoding='utf-8')
(proj / '슬라이드.md').write_text('---\nmarp: true\n---\n\n# 표지\n', encoding='utf-8')
(proj / '제목없음.md').write_text('글만 있는 문서입니다.\n', encoding='utf-8')

server, url, port = serve(proj, base / 'config')
extra = []
try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        page = b.new_page(viewport={'width': 1280, 'height': 820})
        page.on('pageerror', lambda e: extra.append(str(e)[:300]))
        page.goto(url)
        page.wait_for_selector('#lec-tree .row.file', timeout=20000)
        text = lambda: doc.read_text(encoding='utf-8')
        heads = lambda: [s for s in text().split('\n') if s.startswith('#') and '코드 속' not in s]
        toast = lambda: page.text_content('#lec-toast') or ''
        rows = lambda: page.locator('#lec-mdstyle-list li[data-i]').all_inner_texts()
        shown = lambda: [x.strip() for x in page.locator('#lec-mdstyle-preview li').all_inner_texts()]

        def open_doc(name):
            page.locator(f'#lec-tree .row.file[data-doc="{name}"]').click()
            page.wait_for_function("(n) => document.querySelector('#lec-st-path')?.textContent.includes(n)", arg=name, timeout=8000)
            page.wait_for_timeout(500)

        def dialog():
            page.click('#lec-st-mdstyle')
            page.wait_for_selector('#lec-mdstyle-list li[data-i]', timeout=4000)

        def choose(n):
            page.locator('#lec-mdstyle-list li[data-i]').nth(n).click()
            page.wait_for_timeout(120)
            page.click('#lec-mdstyle-go')
            page.wait_for_timeout(300)

        print('[고르기]')
        open_doc('보고서.md')
        check('상태줄에 버튼', page.locator('#lec-st-mdstyle').is_visible())
        dialog()
        check('문서 방식을 본문으로 알아본다', '지금' in page.inner_text('#lec-mdstyle-prose') and '지금' not in page.inner_text('#lec-mdstyle-outline'))
        check('서술식의 머리글 모양', len(rows()) == 5 and all(any(x in r for r in rows()) for x in ('번호 없음', '논문형', '숫자형', '장·절형', '규정형')), rows())
        check('용도가 나온다', '기고문' in rows()[0] and '논문' in rows()[1], rows())
        check('지금 모양을 알린다', '지금' in rows()[0], rows())
        check('미리보기는 지금 문서의 머리글', shown() == ['개요', '배경', '시장 현황'], shown())
        page.locator('#lec-mdstyle-list li[data-i]', has_text='장·절형').click()
        page.wait_for_timeout(150)
        check('고르면 미리보기가 바뀐다', shown() == ['제1장 개요', '제1절 배경', '제2장 시장 현황'], shown())
        check('아직 파일은 그대로', text() == TEXT)
        page.click('#lec-mdstyle-outline')
        page.wait_for_timeout(150)
        check('개조식의 머리글 모양', len(rows()) == 4 and '보고서형' in rows()[0] and '숫자형' in rows()[1] and '기호형' in rows()[2], rows())
        if os.environ.get('LEC_SHOTS'):
            page.screenshot(path=str(Path(os.environ['LEC_SHOTS']) / 'md-문서-스타일.png'))
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        check('Esc 로 닫고 그대로', page.locator('#lec-mdstyle').is_hidden() and text() == TEXT)

        print('[같은 방식 안에서는 바로]')
        dialog()
        choose(3)
        page.wait_for_timeout(900)
        check('묻지 않고 장·절형으로', page.locator('#lec-mdstyle').is_hidden() and heads() == ['# 보고서', '## 제1장 개요', '### 제1절 배경', '## 제2장 시장 현황'], heads())
        check('코드 속 제목과 본문은 그대로', '## 코드 속 제목' in text() and '- 항목입니다' in text() and '글입니다.' in text())
        check('이 문서의 절 링크를 함께 고친다', '[시장으로](#제2장-시장-현황)' in text(), text()[:80])
        check('화면도 바뀐다', page.locator('#lec-view h2').first.inner_text().strip().startswith('제1장 개요'), page.locator('#lec-view h2').first.inner_text())
        check('링크를 알린다', '링크' in toast(), toast())
        page.locator('#lec-view a', has_text='시장으로').click()
        page.wait_for_timeout(400)
        check('고친 링크가 그 절로 간다', page.evaluate("(() => { const h = [...document.querySelectorAll('#lec-view h2')].find((x) => x.textContent.includes('시장 현황')); const r = h.getBoundingClientRect(); return r.top >= 0 && r.top < innerHeight; })()"))
        dialog()
        check('지금 모양을 알아본다', '지금' in rows()[3], rows())
        choose(2)
        page.wait_for_timeout(900)
        check('숫자형으로', heads() == ['# 보고서', '## 1. 개요', '### 1.1 배경', '## 2. 시장 현황'], heads())
        page.locator('#lec-view p').first.click()
        page.keyboard.press('Control+z')
        page.wait_for_timeout(900)
        check('Ctrl+Z 로 되돌린다', heads() == ['# 보고서', '## 제1장 개요', '### 제1절 배경', '## 제2장 시장 현황'], heads())

        print('[방식을 바꾸면 꼭 묻는다]')
        page.evaluate("window.__pasted = []; import('/static/js/store.js').then(({ on }) => on('term-paste', (x) => window.__pasted.push(x)))")
        page.wait_for_timeout(200)
        before = text()
        dialog()
        page.click('#lec-mdstyle-outline')
        page.wait_for_timeout(150)
        choose(0)
        check('바꿀지 묻는다', page.locator('#lec-mdstyle-ask').is_visible() and '바꿀까요' in page.text_content('#lec-mdstyle-question') and 'Claude' in page.text_content('#lec-mdstyle-question'))
        check('Claude 요청이 먼저다', page.evaluate("document.activeElement.id") == 'lec-mdstyle-claude' and page.locator('#lec-mdstyle-ask button').first.get_attribute('id') == 'lec-mdstyle-claude')
        check('선택 항목 셋', all(page.locator(x).is_visible() for x in ('#lec-mdstyle-heads', '#lec-mdstyle-claude', '#lec-mdstyle-no')))
        check('묻는 동안 파일은 그대로', text() == before)
        page.click('#lec-mdstyle-no')
        page.wait_for_timeout(300)
        check('취소하면 그대로', page.locator('#lec-mdstyle').is_hidden() and text() == before)
        dialog()
        page.click('#lec-mdstyle-outline')
        page.wait_for_timeout(150)
        choose(0)
        page.click('#lec-mdstyle-heads')
        page.wait_for_timeout(900)
        check('머리글만 바꾸기', heads() == ['# 보고서', '## Ⅰ. 개요', '### 1. 배경', '## Ⅱ. 시장 현황'], heads())
        check('요청 글은 넣지 않는다', page.evaluate('window.__pasted') == [])
        dialog()
        check('본문이 그대로면 방식도 그대로다', '지금' in page.inner_text('#lec-mdstyle-prose'))
        page.click('#lec-mdstyle-outline')
        page.wait_for_timeout(150)
        choose(1)
        page.click('#lec-mdstyle-claude')
        page.wait_for_timeout(900)
        pasted = page.evaluate('window.__pasted')
        check('머리글을 바꾼다', heads() == ['# 보고서', '## 1. 개요', '### 1.1 배경', '## 2. 시장 현황'], heads())
        check('요청 글만 터미널에 넣는다', len(pasted) == 1 and '@보고서.md' in pasted[0] and '개조식' in pasted[0] and not pasted[0].endswith('\n'), pasted)
        page.keyboard.press('Control+`')
        page.wait_for_timeout(300)
        page.keyboard.press('Control+`')
        page.wait_for_timeout(300)

        print('[이 문서를 스타일로 만들기]')
        own_doc = proj / '회사규정.md'
        own_doc.write_text('# 회사 규정\n\n첫 문단입니다.\n\n둘째 문단입니다.\n\n셋째 문단입니다.\n\n## 제1조 목적\n\n### ① 범위\n\n### ② 정의\n\n## 제2조 시행\n', encoding='utf-8')
        page.wait_for_timeout(1500)
        open_doc('회사규정.md')
        dialog()
        check('지금 모양이 기본에 없으면 표시가 없다', not any('지금' in x for x in rows()), rows())
        check('서술식 문서에서 연다', '지금' in page.inner_text('#lec-mdstyle-prose'))
        page.click('#lec-mdstyle-save')
        page.wait_for_selector('#lec-tplname-input', state='visible', timeout=3000)
        check('뽑은 모양을 보여 주고 이름을 묻는다', '제{1}조' in page.text_content('#lec-tplname-title'), page.text_content('#lec-tplname-title'))
        page.keyboard.type('회사 규정')
        page.keyboard.press('Enter')
        page.wait_for_timeout(600)
        saved = base / 'config' / 'md-styles' / '회사 규정.json'
        check('Lectern 전체의 내 스타일에 파일 하나를 만든다', saved.exists() and '제{1}조' in saved.read_text(encoding='utf-8'))
        check('서술식 스타일로 저장한다', '"prose"' in saved.read_text(encoding='utf-8'), saved.read_text(encoding='utf-8'))
        check('내 스타일 묶음이 나오고 지금 모양이 된다', any('회사 규정' in x and '지금' in x for x in rows()) and page.locator('#lec-mdstyle-list li.head', has_text='내 스타일').count() == 1, rows())
        page.click('#lec-mdstyle-save')
        page.wait_for_selector('#lec-tplname-input', state='visible', timeout=3000)
        page.keyboard.type('회사 규정')
        page.keyboard.press('Enter')
        page.wait_for_timeout(500)
        check('같은 이름은 덮어쓰지 않고 알린다', '같은 이름' in toast(), toast())
        page.keyboard.press('Escape')
        page.wait_for_timeout(300)
        open_doc('보고서.md')
        dialog()
        check('다른 문서에서도 쓴다', any('회사 규정' in x for x in rows()), rows())
        page.locator('#lec-mdstyle-list li[data-i]', has_text='회사 규정').click()
        page.wait_for_timeout(200)
        check('내 스타일의 미리보기', shown()[:2] == ['제1조 개요', '① 배경'], shown())
        page.click('#lec-mdstyle-go')
        page.wait_for_timeout(900)
        check('내 스타일을 입힌다', heads()[1:3] == ['## 제1조 개요', '### ① 배경'], heads())
        page.locator('#lec-view p').first.click()
        page.keyboard.press('Control+z')
        page.wait_for_timeout(900)

        print('[스타일이 많을 때]')
        for i in range(12):
            (base / 'config' / 'md-styles' / f'부서 {i:02d}.json').write_text('{"kind":"prose","marks":["%d조"]}' % i, encoding='utf-8')
        (base / 'config' / 'md-styles' / '깨진파일.json').write_text('{', encoding='utf-8')
        dialog()
        check('많아지면 최근 쓴 것이 위에 나온다', page.locator('#lec-mdstyle-list li.head').first.inner_text() == '최근 쓴 것', page.locator('#lec-mdstyle-list li.head').all_inner_texts())
        check('최근에 쓴 내 스타일이 맨 앞', '회사 규정' in rows()[0], rows()[:2])
        check('깨진 파일은 넘어간다', not any('깨진파일' in x for x in rows()))
        check('목록이 스크롤된다', page.evaluate("(() => { const l = document.querySelector('#lec-mdstyle-list'); return l.scrollHeight > l.clientHeight; })()"))
        page.keyboard.type('부서 0')
        page.wait_for_timeout(300)
        check('이름으로 찾는다', len(rows()) == 10 and all('부서' in x for x in rows()), len(rows()))
        page.keyboard.press('Control+a')
        page.keyboard.type('논문')
        page.wait_for_timeout(300)
        check('용도로 찾는다', 2 <= len(rows()) <= 4 and any('논문형' in x for x in rows()) and any('장·절형' in x for x in rows()), rows())
        page.keyboard.press('Control+a')
        page.keyboard.type('기호')
        page.wait_for_timeout(300)
        check('다른 방식의 스타일도 찾는다', len(rows()) == 1 and '기호형' in rows()[0] and '개조식' in rows()[0], rows())
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        check('Esc 는 찾기를 먼저 지운다', page.locator('#lec-mdstyle').is_visible() and page.input_value('#lec-mdstyle-find') == '')
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)

        print('[복잡하면 Claude 에게 요청]')
        page.evaluate("window.__pasted = []")
        dialog()
        page.click('#lec-mdstyle-request')
        page.wait_for_timeout(400)
        pasted = page.evaluate('window.__pasted')
        check('요청 글만 넣는다', len(pasted) == 1 and '@보고서.md' in pasted[0] and 'md-styles' in pasted[0] and 'writing' in pasted[0] and pasted[0].endswith(': ') and page.locator('#lec-mdstyle').is_hidden(), pasted)
        page.keyboard.press('Control+`')
        page.wait_for_timeout(300)
        page.keyboard.press('Control+`')
        page.wait_for_timeout(300)

        print('[우클릭]')
        page.locator('#lec-view').click(button='right', position={'x': 6, 'y': 6})
        page.wait_for_timeout(200)
        check('문서 메뉴에 있다', 'md 문서 스타일' in page.locator('#lec-menu').inner_text(), page.locator('#lec-menu').inner_text()[:200])
        page.keyboard.press('Escape')

        print('[쓰지 못하는 곳]')
        open_doc('제목없음.md')
        dialog()
        check('머리글이 없으면 알린다', '머리글이 없습니다' in page.text_content('#lec-mdstyle-preview'))
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        open_doc('슬라이드.md')
        page.wait_for_selector('#lec-view.lec-deck', timeout=6000)
        expect(page, 'Lectern 슬라이드에는 없다', lambda: page.locator('#lec-st-mdstyle').is_hidden())
        open_doc('보고서.md')
        expect(page, 'md 문서로 돌아오면 있다', lambda: page.locator('#lec-st-mdstyle').is_visible())
        page.keyboard.press('Control+e')
        expect(page, '편집 중에는 없다', lambda: page.locator('#lec-st-mdstyle').is_hidden(), ms=10000)   # 편집기를 처음 불러올 때는 오래 걸린다
        page.keyboard.press('Escape')
        check('화면 오류 없음', not extra, extra)
        b.close()
except Exception:
    traceback.print_exc()
    fails.append('예외')
finally:
    stop(server, base)
report()
