"""읽는 화면의 기본 키와 칸의 Enter (D158): Home·End·PageUp·PageDown·Space·Ctrl+↑↓ 는 현재 줄과 함께, Shift 를 더하면 고르기, Ctrl+A,
Enter(제목 접기·링크 열기), Tab(다음 링크), F3(다음 찾은 곳), 칸의 Enter 는 새 줄도 저장하고 닫기·Shift+Enter 는 아래에 새 줄, 닫히면 초점은 문서 칸"""
import json
import tempfile
import time
import traceback
from pathlib import Path

from playwright.sync_api import sync_playwright

from harness import check, expect, fails, report, serve, stop, until

base = Path(tempfile.mkdtemp(prefix='lec-viewkeys-'))
proj = base / 'proj'
proj.mkdir(parents=True)
parts = ['# 긴 보고서', '']
for s in range(1, 7):
    parts += [f'## {s}장', '']
    for i in range(1, 9):
        if s == 2 and i == 3:
            parts += ['링크 하나: [다른 문서](b.md) 로 간다.', '']
        elif s == 2 and i == 5:
            parts += ['링크 둘: [첫째](#1장) 와 [셋째](#3장).', '']
        else:
            parts += [f'{s}장 {i}번째 문단이다.', '']
DOC = '\n'.join(parts)
doc = proj / 'a.md'
doc.write_text(DOC, encoding='utf-8')
(proj / 'b.md').write_text('# 다른 문서\n\n다른 문서의 글.\n', encoding='utf-8')
(proj / 'd.md').write_text('# 코드 끝\n\n앞 글.\n\n```\nx = 1\n```\n', encoding='utf-8')
(proj / 'c.py').write_text('\n'.join(f'x{i} = {i}' for i in range(1, 121)) + '\n', encoding='utf-8')
config = base / 'config'
config.mkdir()
(config / 'config.json').write_text(json.dumps({'work_alerts': False}), encoding='utf-8')
server, url, port = serve(proj, config)
LAST = len(parts) - 1   # 마지막 글 줄 (끝의 빈 줄 앞)


def src():
    for _ in range(40):
        try:
            return doc.read_text(encoding='utf-8')
        except OSError:
            time.sleep(0.05)
    return ''


try:
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_context(viewport={'width': 1300, 'height': 760}).new_page()
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)[:300]))
        page.goto(url)
        page.wait_for_selector('#lec-tree .row.file')
        page.locator('#lec-tree .row.file[data-doc="a.md"]').click()
        page.wait_for_selector('#lec-view h1')
        page.wait_for_timeout(700)
        HERE = "() => import('/static/js/store.js').then(({ S }) => S.pane?.here?.line || 0)"
        here = lambda: page.evaluate(HERE)
        lit = lambda: (page.text_content('#lec-st-lit') or '') if page.locator('#lec-st-lit:not([hidden])').count() else ''
        top = lambda: page.evaluate("() => document.querySelector('#lec-content').scrollTop")
        mark_y = lambda: page.evaluate("() => { const m = document.querySelector('.lec-here'); const c = document.querySelector('#lec-content').getBoundingClientRect(); return m ? Math.round(m.getBoundingClientRect().top - c.top) : null; }")
        line_of = lambda text: src().split('\n').index(text) + 1

        def at(text):
            page.keyboard.press('Escape')
            page.keyboard.press('Escape')
            page.locator('#lec-view p, #lec-view h2', has_text=text).first.click()
            page.wait_for_timeout(250)

        print('[옮기기]')
        at('3장 4번째 문단이다.')
        page.keyboard.press('Home')
        page.wait_for_timeout(300)
        check('Home — 현재 줄이 첫 줄, 화면은 맨 위', here() == 1 and top() < 5, (here(), top()))
        page.keyboard.press('End')
        page.wait_for_timeout(300)
        check('End — 현재 줄이 끝 줄', here() == LAST, (here(), LAST))
        page.keyboard.press('Alt+ArrowLeft')
        page.wait_for_timeout(400)
        check('Alt+← — 뛰기 전 자리(첫 줄)로', here() == 1, here())
        at('3장 4번째 문단이다.')
        page.keyboard.press('Control+End')
        page.wait_for_timeout(300)
        page.keyboard.press('Control+Home')
        page.wait_for_timeout(300)
        check('Ctrl+End · Ctrl+Home — 끝 줄과 첫 줄', here() == 1)
        at('1장 3번째 문단이다.')
        y0 = mark_y()
        l0 = here()
        page.keyboard.press('PageDown')
        page.wait_for_timeout(300)
        check('PageDown — 한 화면 아래, 현재 줄은 화면에서 같은 높이', here() > l0 + 6 and abs(mark_y() - y0) < 40, (l0, here(), y0, mark_y()))
        l1 = here()
        page.keyboard.press('Space')
        page.wait_for_timeout(300)
        check('Space — PageDown 과 같다', here() > l1 + 6 and abs(mark_y() - y0) < 40, (l1, here(), mark_y()))
        page.keyboard.press('Shift+Space')
        page.wait_for_timeout(300)
        check('Shift+Space — 한 화면 위', abs(here() - l1) <= 2, (l1, here()))
        for _ in range(30):
            page.keyboard.press('PageDown')
        page.wait_for_timeout(300)
        check('끝에서 PageDown — 끝 줄로', here() == LAST, here())
        at('3장 4번째 문단이다.')
        page.keyboard.press('Control+ArrowDown')
        page.wait_for_timeout(250)
        check('Ctrl+↓ — 다음 제목 (4장)', here() == line_of('## 4장'), here())
        page.keyboard.press('Control+ArrowUp')
        page.wait_for_timeout(250)
        check('Ctrl+↑ — 앞 제목 (3장)', here() == line_of('## 3장'), here())
        page.keyboard.press('Control+ArrowUp')
        page.wait_for_timeout(250)
        check('Ctrl+↑ 한 번 더 — 2장', here() == line_of('## 2장'), here())

        print('[고르기]')
        at('3장 4번째 문단이다.')
        page.keyboard.press('Shift+End')
        page.wait_for_timeout(250)
        check('Shift+End — 끝까지 고르기', lit().startswith(f'고른 줄 {line_of("3장 4번째 문단이다.")}~{LAST}행'), lit())
        at('3장 4번째 문단이다.')
        page.keyboard.press('Shift+Home')
        page.wait_for_timeout(250)
        check('Shift+Home — 처음까지 고르기', lit().startswith(f'고른 줄 1~{line_of("3장 4번째 문단이다.")}행'), lit())
        at('3장 4번째 문단이다.')
        page.keyboard.press('Control+Shift+ArrowDown')
        page.wait_for_timeout(250)
        check('Ctrl+Shift+↓ — 지금 절의 끝까지', lit().startswith(f'고른 줄 {line_of("3장 4번째 문단이다.")}~{line_of("3장 8번째 문단이다.")}행'), lit())
        page.keyboard.press('Control+Shift+ArrowDown')
        page.wait_for_timeout(250)
        check('— 한 번 더 — 다음 절의 끝까지', f'~{line_of("4장 8번째 문단이다.")}행' in lit(), lit())
        at('3장 4번째 문단이다.')
        page.keyboard.press('Control+Shift+ArrowUp')
        page.wait_for_timeout(250)
        check('Ctrl+Shift+↑ — 절 제목까지', lit().startswith(f'고른 줄 {line_of("## 3장")}~{line_of("3장 4번째 문단이다.")}행'), lit())
        at('1장 2번째 문단이다.')
        page.keyboard.press('Shift+PageDown')
        page.wait_for_timeout(250)
        n = int(lit().split(' · ')[-1].rstrip('줄')) if '·' in lit() else 0
        check('Shift+PageDown — 한 화면만큼 고르기', n >= 6, lit())
        page.keyboard.press('PageDown')
        page.wait_for_timeout(250)
        check('고른 채 PageDown — 고르기를 풀고 한 화면', lit() == '', lit())
        at('3장 4번째 문단이다.')
        before_top = top()
        page.keyboard.press('Control+a')
        page.wait_for_timeout(250)
        check('Ctrl+A — 문서의 모든 줄, 화면은 그대로', lit().startswith(f'고른 줄 1~{LAST}행') and abs(top() - before_top) < 5 and not page.evaluate('getSelection().toString()'), (lit(), top(), before_top))

        print('[그 줄에서 하기]')
        page.keyboard.press('Escape')
        page.locator('#lec-view h2', has_text='3장').first.click()
        page.wait_for_timeout(250)
        page.keyboard.press('Enter')
        page.wait_for_timeout(300)
        folded = lambda: page.evaluate("() => !!document.querySelector('#lec-view h2.lec-folded')")
        check('제목 줄의 Enter — 절 접기', folded() and src() == DOC)
        page.keyboard.press('Enter')
        page.wait_for_timeout(300)
        check('— 다시 Enter — 펴기', not folded())
        at('링크 둘:')
        page.keyboard.press('Enter')
        page.wait_for_selector('#lec-menu:not([hidden])', timeout=3000)
        items = page.locator('#lec-menu button').all_inner_texts()
        check('링크가 둘인 줄의 Enter — 고르는 메뉴', [x.strip() for x in items][:2] == ['첫째', '셋째'], items)
        page.keyboard.press('Escape')
        at('2장 2번째 문단이다.')
        page.keyboard.press('Enter')
        page.wait_for_timeout(300)
        check('링크도 제목도 없는 줄의 Enter — 아무 일도 (칸을 열지 않는다)', page.locator('#lec-view .lec-line-edit').count() == 0 and src() == DOC)
        at('2장 2번째 문단이다.')
        page.keyboard.press('Tab')
        page.wait_for_timeout(250)
        check('Tab — 현재 줄 뒤의 다음 링크로, 그 줄이 현재 줄', page.evaluate("document.activeElement?.textContent") == '다른 문서' and here() == line_of('링크 하나: [다른 문서](b.md) 로 간다.'),
              (page.evaluate("document.activeElement?.textContent"), here()))
        page.keyboard.press('Tab')
        page.keyboard.press('Tab')
        page.wait_for_timeout(250)
        check('Tab 두 번 더 — 둘째 줄의 두 번째 링크', page.evaluate("document.activeElement?.textContent") == '셋째')
        page.keyboard.press('Shift+Tab')
        page.wait_for_timeout(250)
        check('Shift+Tab — 앞 링크', page.evaluate("document.activeElement?.textContent") == '첫째')
        page.keyboard.press('Enter')
        page.wait_for_timeout(500)
        check('초점이 링크에 있으면 Enter — 그 링크 (1장으로)', here() == line_of('## 1장') or abs(top()) < 400, (here(), top()))
        at('링크 하나:')
        page.keyboard.press('Enter')
        expect(page, '링크가 하나인 줄의 Enter — 그 문서가 열린다', lambda: '다른 문서' in (page.text_content('#lec-view h1') or ''))
        page.keyboard.press('Alt+ArrowLeft')
        page.wait_for_selector('#lec-view h1:has-text("긴 보고서")')
        page.wait_for_timeout(500)

        print('[찾기]')
        at('1장 1번째 문단이다.')
        page.keyboard.press('F3')
        page.wait_for_timeout(250)
        check('찾은 말이 없을 때 F3 — 알림', '찾은 말이 없습니다' in (page.text_content('#lec-toast') or ''))
        page.keyboard.press('Control+f')
        page.keyboard.type('5번째')
        page.wait_for_timeout(400)
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        page.locator('#lec-view p', has_text='1장 1번째 문단이다.').click()
        page.keyboard.press('F3')
        page.wait_for_timeout(300)
        c1 = page.text_content('#lec-find-count') or ''
        page.keyboard.press('F3')
        page.wait_for_timeout(300)
        c2 = page.text_content('#lec-find-count') or ''
        page.keyboard.press('Shift+F3')
        page.wait_for_timeout(300)
        c3 = page.text_content('#lec-find-count') or ''
        check('F3 · F3 · Shift+F3 — 찾기 막대를 닫아도 다음·앞 찾은 곳', c1 and c2 and c3 == c1 and c1 != c2, (c1, c2, c3))
        page.keyboard.press('Escape')

        print('[칸의 Enter · Shift+Enter, 닫힌 뒤 초점]')
        at('4장 2번째 문단이다.')
        line = here()
        page.keyboard.press('F2')
        page.wait_for_selector('#lec-view .lec-line-edit')
        page.keyboard.press('End')
        page.keyboard.type(' 더')
        page.keyboard.press('Enter')
        until(page, lambda: '4장 2번째 문단이다. 더' in src(), 6000)
        page.wait_for_timeout(400)
        check('F2 → Enter — 저장하고 현재 줄은 그 줄, 초점은 문서 칸', here() == line and page.evaluate('document.activeElement?.id') == 'lec-content', (here(), page.evaluate('document.activeElement?.id')))
        page.keyboard.press('ArrowDown')
        page.wait_for_timeout(250)
        check('— 이어서 ↓ 가 그 줄에서', here() == line + 2, here())
        page.keyboard.press('Control+Enter')
        page.wait_for_selector('#lec-view .lec-line-edit')
        page.keyboard.type('새 줄 하나')
        page.keyboard.press('Enter')
        until(page, lambda: '새 줄 하나' in src(), 6000)
        page.wait_for_timeout(500)
        check('새 줄의 Enter — 저장하고 닫는다 (다음 새 줄을 열지 않음)', page.locator('#lec-view .lec-line-edit').count() == 0 and here() == line_of('새 줄 하나'), (page.locator('#lec-view .lec-line-edit').count(), here()))
        page.keyboard.press('F2')
        page.wait_for_selector('#lec-view .lec-line-edit')
        page.keyboard.press('End')
        page.keyboard.press('Shift+Enter')
        page.wait_for_timeout(500)
        page.keyboard.type('둘째 새 줄')
        page.keyboard.press('Shift+Enter')
        page.wait_for_timeout(600)
        page.keyboard.type('셋째 새 줄')
        page.keyboard.press('Enter')
        until(page, lambda: '셋째 새 줄' in src(), 6000)
        page.wait_for_timeout(500)
        check('Shift+Enter 로 이어 쓰고 Enter 로 끝 — 세 줄이 차례로', '새 줄 하나\n\n둘째 새 줄\n\n셋째 새 줄\n' in src() and page.locator('#lec-view .lec-line-edit').count() == 0 and here() == line_of('셋째 새 줄'),
              (src()[src().find('새 줄 하나') - 2:src().find('새 줄 하나') + 40], here()))
        page.keyboard.press('Control+Enter')
        page.wait_for_selector('#lec-view .lec-line-edit')
        page.keyboard.press('Enter')
        page.wait_for_timeout(400)
        check('빈 새 줄의 Enter — 넣지 않고 닫는다', page.locator('#lec-view .lec-line-edit').count() == 0 and src().count('\n\n\n') == 0)
        before = src()
        page.keyboard.press('.')
        page.wait_for_selector('#lec-put:not([hidden])')
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        check('바꾸기 창을 닫으면 초점은 문서 칸', page.evaluate('document.activeElement?.id') == 'lec-content' and src() == before)

        print('[문서 끝 — 중간과 같은 키]')
        at('6장 8번째 문단이다.')
        page.evaluate("document.querySelector('#lec-toast').textContent = ''")
        page.keyboard.press('ArrowDown')
        page.wait_for_timeout(300)
        check('끝 줄의 ↓ — 새 줄을 열지 않고 Ctrl+Enter 를 알린다', page.locator('#lec-view .lec-line-edit').count() == 0 and 'Ctrl+Enter' in (page.text_content('#lec-toast') or ''), page.text_content('#lec-toast'))
        page.keyboard.press('F2')
        page.wait_for_selector('#lec-view .lec-line-edit')
        page.evaluate("document.querySelector('#lec-toast').textContent = ''")
        page.keyboard.press('ArrowDown')
        page.wait_for_timeout(300)
        check('칸에서 끝 줄의 ↓ — 칸은 그대로, Shift+Enter 를 알린다', page.locator('#lec-view .lec-line-edit').count() == 1 and 'Shift+Enter' in (page.text_content('#lec-toast') or ''), page.text_content('#lec-toast'))
        page.keyboard.press('Escape')
        page.wait_for_timeout(300)
        page.evaluate("() => import('/static/js/store.js').then((m) => m.emit('open', { type: 'doc', path: 'd.md' }))")
        page.wait_for_selector('#lec-view h1:has-text("코드 끝")')
        page.wait_for_timeout(500)
        page.locator('#lec-view pre code').first.click()
        page.wait_for_timeout(200)
        page.keyboard.press('/')
        page.wait_for_selector('#lec-put:not([hidden])', timeout=3000)
        page.keyboard.type('문단')
        page.wait_for_timeout(150)
        page.keyboard.press('Enter')
        page.wait_for_timeout(400)
        page.keyboard.type('코드 뒤 글')
        page.keyboard.press('Enter')
        dmd = proj / 'd.md'
        until(page, lambda: '코드 뒤 글' in dmd.read_text(encoding='utf-8'), 6000)
        check('문서 끝의 코드 블록에서 / — 블록 뒤에 문단', dmd.read_text(encoding='utf-8').endswith('```\nx = 1\n```\n\n코드 뒤 글\n'), dmd.read_text(encoding='utf-8'))

        print('[코드 화면]')
        page.locator('#lec-tree .row.file', has_text='c.py').first.click() if page.locator('#lec-tree .row.file', has_text='c.py').count() else None
        if page.locator('#lec-view.code-view').count() == 0:
            page.evaluate("() => import('/static/js/store.js').then((m) => m.emit('open', { type: 'code', path: 'c.py' }))")
        page.wait_for_selector('#lec-view.code-view .cv-line', timeout=8000)
        page.wait_for_timeout(500)
        page.locator('#lec-view .cv-line').nth(10).click()
        page.keyboard.press('End')
        page.wait_for_timeout(300)
        check('코드 화면의 End — 끝 줄', here() == 120, here())
        page.keyboard.press('Home')
        page.wait_for_timeout(300)
        check('코드 화면의 Home — 첫 줄', here() == 1, here())
        check('화면 스크립트 오류 없음', not errors, errors[:3])
        browser.close()
except Exception:
    traceback.print_exc()
    fails.append('예외')
finally:
    stop(server, base)
report()
