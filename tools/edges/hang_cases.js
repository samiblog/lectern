// hang.js 의 머리 글자 (D191 — rules_check.mjs 가 돈다. m: hang.js, 끝에서 {n, fails} 를 돌려준다).
// 머리 글자로 읽는 것과 읽지 않는 것, 그리고 어림한 폭의 크기 차례.
const { hangPrefix, hangEm, blockHang } = m;
let n = 0;
const fails = [];
const eq = (got, want, name) => {
  n += 1;
  if (JSON.stringify(got) !== JSON.stringify(want)) fails.push(`${name}: ${JSON.stringify(got)} ≠ ${JSON.stringify(want)}`);
};
const T = '산업별 생산성은 다르다';

// ---- 머리 글자로 읽는 것 ----
for (const [text, want, name] of [
  [`1. ${T}`, '1. ', '번호'],
  [`12. ${T}`, '12. ', '두 자리 번호'],
  [`100. ${T}`, '100. ', '세 자리 번호'],
  [`1.2 ${T}`, '1.2 ', "'1.2' 꼴 (점 없이) — '1.' 에서 멈추지 않는다"],
  [`1.2. ${T}`, '1.2. ', "'1.2.' 꼴"],
  [`1-1. ${T}`, '1-1. ', "'1-1.' 꼴"],
  [`2-3) ${T}`, '2-3) ', "'2-3)' 꼴"],
  [`(1) ${T}`, '(1) ', '괄호 번호'],
  [`1) ${T}`, '1) ', '닫는 괄호 번호'],
  [`[3] ${T}`, '[3] ', '참고 문헌 번호'],
  [`가. ${T}`, '가. ', '가나다 번호'],
  [`(나) ${T}`, '(나) ', '괄호 가나다'],
  [`다) ${T}`, '다) ', '닫는 괄호 가나다'],
  [`A. ${T}`, 'A. ', '영문 대문자'],
  [`(a) ${T}`, '(a) ', '괄호 영문'],
  [`Ⅲ. ${T}`, 'Ⅲ. ', '로마 숫자 글자'],
  [`IV. ${T}`, 'IV. ', '로마 숫자 (영문)'],
  [`제2장 ${T}`, '제2장 ', '제N장'],
  [`□ ${T}`, '□ ', '네모'],
  [`○ ${T}`, '○ ', '동그라미'],
  [`ㅇ ${T}`, 'ㅇ ', '이응 글머리 (공문서)'],
  [`- ${T}`, '- ', '붙임표'],
  [`• ${T}`, '• ', '가운뎃점 글머리'],
  [`※ ${T}`, '※ ', '참고표'],
  [`※${T}`, '※', '참고표는 붙여 써도'],
  [`①${T}`, '①', '둥근 번호는 붙여 써도'],
  [`⑵ ${T}`, '⑵ ', '괄호 번호 글자'],
  [`㉠ ${T}`, '㉠ ', '둥근 한글'],
  [`  ○ ${T}`, '○ ', '앞의 빈칸은 세지 않는다'],
  [`○  ${T}`, '○  ', '줄 바꿈 없는 빈칸은 그대로'],
  [`1.   ${T}`, '1.   ', '이어진 빈칸'],
]) eq(hangPrefix(text), want, name);

// ---- 읽지 않는 것 ----
for (const [text, name] of [
  [T, '머리 글자가 없는 글'],
  ['3 가지 이유가 있다', "'3 가지' 는 번호가 아니다"],
  ['2024년 매출은 늘었다', "'2024년'"],
  ['2024. 11. 22. 회의', '네 자리 수는 번호가 아니다'],
  ['○○ 기관의 보고서', "'○○' 의 ○ 는 글머리가 아니다 (빈칸이 없다)"],
  ['1.5배 늘었다', "'1.5배'"],
  ['e.g. 예를 들면', "'e.g.'"],
  ['가나다 순서로', "'가나다'"],
  ['- ', '머리 글자뿐 (꺾일 글이 없다)'],
  ['①', '둥근 번호뿐'],
  ['1.', '번호뿐'],
  ['-1도까지 내려간다', "'-1도' (빈칸이 없다)"],
  ['I am fine', "영문 'I' (점이 없다)"],
  ['0.50 은 같은 주소를 읽었다', "판 번호 '0.50'"],
  ['0.50.0 이 한 것', "판 번호 '0.50.0'"],
  ['1.0 판에서', "자리에 0 이 든 수 '1.0'"],
  ['8-1 의 선택 사항은 미룬다', "글 속의 '8-1' (붙임표 꼴은 점이 있어야)"],
]) eq(hangPrefix(text), '', name);

// ---- 어림한 폭 ----
eq(hangEm('1. ') < hangEm('12. '), true, '두 자리 번호가 더 넓다');
eq(hangEm('• ') < hangEm('□ ') && hangEm('□ ') < hangEm('① '), true, '• < □ < ① (잰 평균의 차례)');
eq(hangEm('1.   '), hangEm('1. '), '이어진 빈칸은 화면에서 하나');
eq(hangEm('○  ') > hangEm('○ '), true, '줄 바꿈 없는 빈칸은 하나하나');
eq(hangEm('제1장 ') > 2 && hangEm('제1장 ') < 3, true, "'제1장 ' 은 2~3em");

// ---- 줄바꿈으로 나뉜 줄이 여럿인 블록 (breaks — 한 문단에 □·○·- 줄) ----
const LONG = '인공지능 확산은 산업 전반의 생산성을 끌어올리지만 그 효과는 다르다';
eq(blockHang(`□ 추진 배경\n○ ${LONG}\n- 세부`), { prefix: '○ ', at: 8 }, '줄마다 다르면 가장 긴 줄의 머리 글자');
eq(blockHang(`다음과 같다\n① ${LONG}\n② ${LONG}`), { prefix: '① ', at: 7 }, '첫 줄이 머리 글자 없는 짧은 줄이고 나머지가 ①·②');
eq(blockHang(`${LONG}\n① 짧은 줄\n${LONG}`), null, '첫 줄에 없고 반 넘게 있지도 않으면 내어 쓰지 않는다');
eq(blockHang(`  ※ ${LONG}`), { prefix: '※ ', at: 2 }, '앞의 빈칸 뒤의 자리');
eq(blockHang(LONG), null, '머리 글자가 없는 블록');
return { n, fails };
