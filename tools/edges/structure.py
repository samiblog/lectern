def text_of(name):
    for _ in range(40):
        try:
            return files[name].read_bytes().decode('utf-8')
        except OSError:   # 앱이 파일을 바꿔 끼우는 순간 (ReplaceFileW)
            time.sleep(0.05)
    raise RuntimeError(name)


def until(name, want, page, ms=5000):
    """파일이 want 가 될 때까지 (page 로 기다려 가로챈 요청이 돌게)"""
    end = time.time() + ms / 1000
    got = None
    while time.time() < end:
        got = text_of(name)
        if got == want:
            return True
        page.wait_for_timeout(40)
    print('    파일:', repr(got), flush=True)
    return False


