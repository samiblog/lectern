"""0.69: 캡션 번호와 상호 참조, 본문 인용, 문서 안 목차·쪽 나눔, 목차에서 절 끌기, vi 키 (D121·D122)."""
import json
import re
import tempfile
import traceback
import urllib.request
from pathlib import Path

from playwright.sync_api import sync_playwright

from harness import check, fails, report, serve, stop

base = Path(tempfile.mkdtemp(prefix='lec-refsvi-'))
proj = base / 'proj'
proj.mkdir(parents=True)
doc = proj / '보고.md'
TABLES = ('# 보고\n\n## 가\n\n가 글\n\n표 1. 첫 표\n\n| a |\n| --- |\n| 1 |\n\n## 나\n\n나 글\n\n표 2. 둘째 표\n\n| b |\n| --- |\n| 2 |\n\n'
          '[표 2](#표-2) 참조, 표 2 글자\n')
doc.write_text(TABLES, encoding='utf-8')
(proj / '빈.md').write_text('# 빈\n\n글\n', encoding='utf-8')

server, url, port = serve(proj, base / 'config')
extra = []


def config(**values):
    req = urllib.request.Request(url + 'api/config', data=json.dumps(values).encode(), headers={'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=10) as r:
        return r.status


try:
    with sync_playwright() as p:
        b = p.chromium.launch()
        page = b.new_context(viewport={'width': 1280, 'height': 820}, permissions=['clipboard-read', 'clipboard-write']).new_page()
        page.on('pageerror', lambda e: extra.append(str(e)[:300]))
        page.goto(url)
        page.wait_for_selector('#lec-tree .row.file', timeout=20000)
        src = lambda: doc.read_text(encoding='utf-8')
        cells = lambda: page.evaluate("[...document.querySelectorAll('#lec-view .lec-line-edit')].map((e) => e.textContent)")
        toast = lambda: page.text_content('#lec-toast') or ''

        def open_doc(name):
            page.locator(f'#lec-tree .row.file[data-doc="{name}"]').click()
            page.wait_for_function("(n) => document.querySelector('#lec-st-path')?.textContent.includes(n)", arg=name, timeout=8000)
            page.wait_for_timeout(400)

        def put(text):
            page.keyboard.press('Escape')
            page.keyboard.press('Escape')
            doc.write_text(text, encoding='utf-8')
            page.wait_for_timeout(1300)

        def choose(word):
            page.keyboard.press('/')
            page.wait_for_selector('#lec-put:not([hidden])', timeout=3000)
            page.keyboard.type(word)
            page.wait_for_timeout(150)
            page.keyboard.press('Enter')
            page.wait_for_timeout(600)

        def new_line_after(selector):
            page.locator(selector).first.click()
            page.wait_for_timeout(200)
            page.keyboard.press('Control+Enter')
            page.wait_for_timeout(400)

        open_doc('보고.md')

        print('[캡션 번호]')
        check('캡션 단락에 참조 자리 id', page.evaluate("!!document.querySelector('#lec-view p[id=\"표-1\"]') && !!document.querySelector('#lec-view p[id=\"표-2\"]')"))
        new_line_after('#lec-view p:text-is("가 글")')
        choose('표')
        page.wait_for_selector('#lec-put:not([hidden])', timeout=3000)
        page.keyboard.press('Control+a')
        page.keyboard.type('1x1')
        page.keyboard.press('Enter')
        page.wait_for_timeout(1000)
        s = src()
        check('위에 넣은 표가 1번, 뒤 표는 2·3번', s.index('표 1. 제목') < s.index('표 2. 첫 표') < s.index('표 3. 둘째 표'), s)
        check('참조 링크가 따라간다', '[표 3](#표-3) 참조' in s, s)
        check('링크가 아닌 글자는 그대로', '표 2 글자' in s, s)
        check('고치지 않은 글자를 알린다', 'Ctrl+F' in toast(), toast())
        page.keyboard.press('Escape')
        page.keyboard.press('Control+z')
        page.wait_for_timeout(900)
        check('한 번의 Ctrl+Z 로 번호까지 되돌린다', src() == TABLES, src())

        print('[상호 참조]')
        put(TABLES)
        new_line_after('#lec-view p:text-is("나 글")')
        page.keyboard.type('앞의 ')
        page.keyboard.press('Control+Shift+/')
        page.wait_for_selector('#lec-put:not([hidden])', timeout=3000)
        page.keyboard.type('상호')
        page.keyboard.press('Enter')
        page.wait_for_timeout(300)
        listed = page.inner_text('#lec-put-list')
        check('표와 절을 고른다', '표 1. 첫 표' in listed and '가' in listed and '표·그림' in listed, listed[:200])
        page.keyboard.type('첫 표')
        page.wait_for_timeout(120)
        page.keyboard.press('Enter')
        page.wait_for_timeout(200)
        check('칸에 링크가 들어간다', cells() == ['앞의 [표 1](#표-1)'], cells())
        page.keyboard.press('Enter')
        page.wait_for_timeout(900)
        check('저장된다', '앞의 [표 1](#표-1)\n' in src(), src())
        page.keyboard.press('Escape')
        page.wait_for_timeout(300)
        page.locator('#lec-view a:text-is("표 1")').first.click()
        page.wait_for_timeout(500)
        top = page.evaluate("document.querySelector('#lec-view p[id=\"표-1\"]').getBoundingClientRect().top")
        check('링크를 누르면 그 캡션으로', 0 <= top < 300, top)

        print('[본문 인용]')
        BIB = '# 글\n\n본문 (김영삼, 2026).\n\n## 참고문헌\n\n- 김영삼 (2026). 철도 수요.\n- Kim, Y., & Lee, S. (2024). Demand.\n'
        put(BIB)
        new_line_after('#lec-view p:text-is("본문 (김영삼, 2026).")')
        page.keyboard.type('그리고 ')
        page.keyboard.press('Control+Shift+/')
        page.wait_for_selector('#lec-put:not([hidden])', timeout=3000)
        page.keyboard.type('본문 인용')
        page.keyboard.press('Enter')
        page.wait_for_timeout(300)
        title = page.text_content('#lec-put-title') or ''
        listed = page.inner_text('#lec-put-list')
        check('안 쓴 문헌을 알린다', '1개는 본문에 아직 없습니다' in title and '아직 안 씀' in listed and '본문 1곳' in listed, (title, listed[:200]))
        page.keyboard.type('Demand')
        page.wait_for_timeout(120)
        page.keyboard.press('Enter')
        page.wait_for_timeout(200)
        check('인용 글자가 들어간다', cells() == ['그리고 (Kim & Lee, 2024)'], cells())
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)

        print('[목차·쪽 나눔]')
        put('# 보고\n\n## 가\n\n가 글\n\n### 가-1\n\n그림 1. 사진\n\n## 나\n\n나 글\n')
        page.locator('#lec-view h2').first.click()
        page.wait_for_timeout(200)
        page.keyboard.press('Control+Shift+Enter')
        page.wait_for_timeout(400)
        choose('목차')
        page.keyboard.press('Escape')
        page.wait_for_timeout(900)
        check('[목차] 한 줄이 들어간다', '\n[목차]\n' in src(), src())
        toc = page.evaluate("[...document.querySelectorAll('#lec-view nav.lec-doctoc li')].map((li) => li.className + ':' + li.textContent)")
        check('목차가 제목으로 그려진다 (문서 제목은 빼고)', toc == ['d0:가', 'd1:가-1', 'd0:나'], toc)
        check('목차 줄은 줄 하나로 고른다', page.evaluate("document.querySelector('#lec-view nav.lec-doctoc')?.dataset.lines") is not None)
        put('# 보고\n\n가 글\n\n<div style="page-break-after: always;"></div>\n\n뒤 글\n\n[그림 목차]\n\n그림 1. 사진\n')
        check('쪽 나눔 줄이 점선으로', page.evaluate("document.querySelector('#lec-view .lec-pagebreak')?.textContent") == '쪽 나눔')
        check('인쇄에서 쪽이 바뀐다', page.evaluate("""(() => { const s = [...document.styleSheets].flatMap((x) => { try { return [...x.cssRules]; } catch { return []; } });
            return s.some((r) => r.media && [...r.media].includes('print') && r.cssText.includes('lec-pagebreak') && r.cssText.includes('break-after: page')); })()"""))
        figs = page.evaluate("[...document.querySelectorAll('#lec-view nav.lec-doctoc a')].map((a) => a.getAttribute('href'))")
        check('그림 목차는 캡션으로', figs == ['#그림-1'], figs)

        print('[목차에서 절 끌기]')
        put('# 글\n\n## 첫째\n\n가\n\n## 둘째\n\n나\n\n## 셋째\n\n다\n')
        page.wait_for_selector('#lec-toc a[data-i]', timeout=5000)
        third = page.locator('#lec-toc a[data-i]', has_text='셋째')
        first = page.locator('#lec-toc a[data-i]', has_text='첫째')
        check('md 문서의 제목은 끌 수 있다', first.get_attribute('draggable') == 'true')
        third.drag_to(first, target_position={'x': 10, 'y': 2})
        page.wait_for_timeout(1000)
        check('셋째 절이 첫째 앞으로', src() == '# 글\n\n## 셋째\n\n다\n\n## 첫째\n\n가\n\n## 둘째\n\n나\n', src())
        page.keyboard.press('Control+z')
        page.wait_for_timeout(900)
        check('Ctrl+Z 로 되돌린다', src() == '# 글\n\n## 첫째\n\n가\n\n## 둘째\n\n나\n\n## 셋째\n\n다\n', src())

        print('[vi 키 — 꺼져 있을 때]')
        put('# 글\n\n첫 줄\n\n둘째 줄\n\n셋째 줄\n')
        page.locator('#lec-view p:text-is("첫 줄")').click()
        page.wait_for_timeout(200)
        def here():
            m = re.search(r'(\d+)', page.text_content('#lec-st-here') or '')
            return int(m.group(1)) if m else None

        before = here()
        page.keyboard.press('j')
        page.keyboard.press('d')
        page.keyboard.press('d')
        page.wait_for_timeout(600)
        check('기본은 꺼짐 — 글자 키는 아무 일도 하지 않는다', here() == before and src() == '# 글\n\n첫 줄\n\n둘째 줄\n\n셋째 줄\n' and page.locator('#lec-st-vi').is_hidden(), (before, here(), src()))

        print('[vi 키 — 켜면]')
        page.keyboard.press('Control+,')
        page.wait_for_selector('#lec-settings:not([hidden])', timeout=3000)
        page.locator('#lec-settings input[data-key="vi_keys"]').check()
        page.wait_for_timeout(300)
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        check('설정에 저장된다', json.loads((base / 'config' / 'config.json').read_text(encoding='utf-8')).get('vi_keys') is True)
        check('상태줄에 vi', page.locator('#lec-st-vi').is_visible() and page.text_content('#lec-st-vi') == 'vi')
        page.locator('#lec-view p:text-is("첫 줄")').click()
        page.wait_for_timeout(200)
        page.keyboard.press('j')
        page.wait_for_timeout(200)
        check('j 로 아래 줄', here() == 5, here())
        page.keyboard.press('k')
        page.wait_for_timeout(200)
        check('k 로 위 줄', here() == 3, here())
        page.keyboard.press('Shift+G')
        page.wait_for_timeout(200)
        check('G 로 끝 줄', here() == 7, here())
        page.keyboard.press('g')
        check('앞 글자를 기다리는 동안 상태줄에', page.text_content('#lec-st-vi') == 'vi g…', page.text_content('#lec-st-vi'))
        page.keyboard.press('g')
        page.wait_for_timeout(200)
        check('gg 로 첫 줄', here() == 1 and page.text_content('#lec-st-vi') == 'vi', here())
        page.keyboard.press('j')
        page.wait_for_timeout(200)
        page.keyboard.press('d')
        page.keyboard.press('d')
        page.wait_for_timeout(900)
        check('dd 로 그 줄을 지운다', src() == '# 글\n\n둘째 줄\n\n셋째 줄\n', src())
        page.keyboard.press('u')
        page.wait_for_timeout(900)
        check('u 로 되돌린다', src() == '# 글\n\n첫 줄\n\n둘째 줄\n\n셋째 줄\n', src())
        page.locator('#lec-view p:text-is("첫 줄")').click()
        page.wait_for_timeout(200)
        page.keyboard.press('y')
        page.keyboard.press('y')
        page.wait_for_timeout(300)
        page.keyboard.press('Shift+G')
        page.wait_for_timeout(200)
        page.keyboard.press('p')
        page.wait_for_timeout(900)
        check('yy 로 담고 p 로 아래에 넣는다', src() == '# 글\n\n첫 줄\n\n둘째 줄\n\n셋째 줄\n\n첫 줄\n', src())
        page.keyboard.press('u')
        page.wait_for_timeout(900)
        page.locator('#lec-view p:text-is("둘째 줄")').click()
        page.wait_for_timeout(200)
        page.keyboard.press('Shift+V')
        page.wait_for_timeout(200)
        page.keyboard.press('j')
        page.wait_for_timeout(200)
        page.keyboard.press('d')
        page.wait_for_timeout(900)
        check('V 로 고르고 j 로 넓혀 d 로 지운다', src() == '# 글\n\n첫 줄\n', src())
        page.keyboard.press('u')
        page.wait_for_timeout(900)
        page.locator('#lec-view p:text-is("첫 줄")').click()
        page.wait_for_timeout(200)
        page.keyboard.press('o')
        page.wait_for_timeout(400)
        check('o 로 아래에 새 줄', cells() == [''], cells())
        page.keyboard.type('새 글')
        page.keyboard.press('Escape')
        page.wait_for_timeout(900)
        check('칸의 Esc 는 저장하고 나온다', '첫 줄\n\n새 글\n' in src() and cells() == [], (src(), cells()))
        page.locator('#lec-view p:text-is("새 글")').click()
        page.wait_for_timeout(200)
        page.keyboard.press('a')
        page.wait_for_timeout(400)
        page.keyboard.type('!')
        page.keyboard.press('Escape')
        page.wait_for_timeout(900)
        check('a 로 줄 끝에 쓴다', '새 글!\n' in src(), src())
        page.keyboard.press('Control+,')
        page.wait_for_selector('#lec-settings:not([hidden])', timeout=3000)
        page.locator('#lec-settings input[data-key="vi_keys"]').uncheck()
        page.wait_for_timeout(300)
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        check('끄면 상태줄에서 사라진다', page.locator('#lec-st-vi').is_hidden())
        kept = src()
        page.locator('#lec-view p:text-is("새 글!")').click()
        page.wait_for_timeout(200)
        page.keyboard.press('F2')
        page.wait_for_timeout(400)
        page.keyboard.type('x')
        page.keyboard.press('Escape')
        page.wait_for_timeout(700)
        check('끄면 칸의 Esc 는 다시 그만두기', src() == kept, src())

        print('[전체 편집의 vim]')
        config(vi_keys=True)
        page.reload()
        page.wait_for_selector('#lec-tree .row.file', timeout=20000)
        open_doc('빈.md')
        page.keyboard.press('Control+e')
        page.wait_for_selector('.lec-editor .CodeMirror', timeout=8000)
        page.wait_for_timeout(500)
        check('vim 키맵', page.evaluate("document.querySelector('.lec-editor .CodeMirror').CodeMirror.getOption('keyMap')") == 'vim')
        page.keyboard.press('Escape')
        page.wait_for_timeout(200)
        check('Esc 는 편집을 닫지 않는다 (Normal 모드로)', page.locator('.lec-editor').count() == 1)
        page.keyboard.press('Shift+G')
        page.keyboard.press('o')
        page.keyboard.type('vim 줄')
        page.keyboard.press('Escape')
        page.keyboard.type(':w')
        page.keyboard.press('Enter')
        page.wait_for_timeout(900)
        check(':w 로 저장', 'vim 줄' in (proj / '빈.md').read_text(encoding='utf-8'), (proj / '빈.md').read_text(encoding='utf-8'))
        page.keyboard.type(':q')
        page.keyboard.press('Enter')
        page.wait_for_timeout(500)
        check(':q 로 닫는다', page.locator('.lec-editor').count() == 0)

        check('화면 오류 없음', not extra, extra)
        b.close()
except Exception:
    traceback.print_exc()
    fails.append('예외')
finally:
    stop(server, base)
report()
