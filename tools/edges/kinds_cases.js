// 구성 요소 바꾸기의 표 점검 (D155) — rules_check.mjs 가 돌린다 (d: docops.js, lo: lineops.js)
// 고른 줄만 바꾸고 이웃은 뜻이 깨질 때만 따라 고친다: 번호 잇기, 이웃 목록에 붙기, 강조글·인용 안에서 바꾸기, 덩어리 바꾸기, 위에 넣는 새 줄
const { setKind, listToTable, tableToList, wrapCode, unwrapCode } = d;
const { relist, planNew, insertLine } = lo;
const fails = [];
let n = 0;
const same = (name, got, want) => {
  n += 1;
  const a = JSON.stringify(got);
  const b = JSON.stringify(want);
  if (a !== b) fails.push(`${name}: ${a} ≠ ${b}`);
};
const L = (s) => s.split('\n');
const J = (r) => (r.error ? r.error : r.lines.join('\n'));
const K = (src, a, b, kind) => J(setKind(L(src), a, b, kind));

// ---- 번호 목록에서 줄이 빠지면 뒤 항목을 앞 항목에 잇는다 ----
same('K1 가운데 항목을 문단으로', K('1. 가\n2. 나\n3. 다\n4. 라', 2, 2, 'para'), '1. 가\n\n나\n\n2. 다\n3. 라');
same('K2 가운데 항목을 제목으로', K('1. 가\n2. 나\n3. 다', 2, 2, 'h2'), '1. 가\n\n## 나\n\n2. 다');
same('K3 가운데 항목을 글머리로', K('1. 가\n2. 나\n3. 다\n4. 라', 2, 2, 'bullet'), '1. 가\n- 나\n2. 다\n3. 라');
same('K4 첫 항목을 문단으로 — 뒤는 처음 번호부터', K('1. 가\n2. 나\n3. 다', 1, 1, 'para'), '가\n\n1. 나\n2. 다');
same('K5 5부터 시작한 목록', K('5. 가\n6. 나\n7. 다', 2, 2, 'para'), '5. 가\n\n나\n\n6. 다');
same('K6 모두 1. 로 쓴 목록은 그대로', K('1. 가\n1. 나\n1. 다', 2, 2, 'para'), '1. 가\n\n나\n\n1. 다');
same('K7 바꾼 수 — 고른 줄 밖에서 번호가 바뀐 항목', setKind(L('1. 가\n2. 나\n3. 다\n4. 라'), 2, 2, 'para').renumbered, 2);
same('K8 하위 번호 항목은 부모 항목 안의 문단으로', K('- 가\n  1. 가1\n  2. 가2\n  3. 가3', 3, 3, 'para'), '- 가\n  1. 가1\n\n  가2\n\n  2. 가3');

// ---- 바로 위·아래가 같은 종류의 목록이면 붙는다 ----
same('K9 번호 목록 아래 문단을 번호로', K('1. 가\n2. 나\n\n다', 4, 4, 'number'), '1. 가\n2. 나\n3. 다');
same('K10 빈 줄로 띄운 번호 목록 — 빈 줄 하나', K('1. 가\n\n2. 나\n\n다', 5, 5, 'number'), '1. 가\n\n2. 나\n\n3. 다');
same('K11 위아래 번호 목록 사이 — 하나로 잇고 뒤 번호', K('1. 가\n2. 나\n\n다\n\n3. 라\n4. 마', 4, 4, 'number'), '1. 가\n2. 나\n3. 다\n4. 라\n5. 마');
same('K12 * 목록에 붙으면 * 표시', K('* 가\n* 나\n\n다', 4, 4, 'bullet'), '* 가\n* 나\n* 다');
same('K13 글머리 목록 아래를 번호로 — 붙지 않음', K('- 가\n- 나\n\n다', 4, 4, 'number'), '- 가\n- 나\n\n1. 다');
same('K14 할 일 목록에 할 일로', K('- [ ] 가\n- [x] 나\n\n다', 4, 4, 'task'), '- [ ] 가\n- [x] 나\n- [ ] 다');
same('K15 항목 하나뿐인 목록 — 있던 빈 줄은 그대로', K('- a\n\n글', 3, 3, 'bullet'), '- a\n\n- 글');
same('K16 항목의 이어진 줄을 항목으로 — 겹치지 않음', K('1. a\n글', 2, 2, 'number'), '1. a\n2. 글');
same('K17 하위가 있는 위 항목에 붙는다 (항목 하나 — 빈 줄은 그대로)', K('- 가\n  - 가1\n\n나', 4, 4, 'bullet'), '- 가\n  - 가1\n\n- 나');
same('K17b 하위가 있는 항목 둘인 목록에 붙는다', K('- 가\n  - 가1\n- 나\n\n다', 5, 5, 'bullet'), '- 가\n  - 가1\n- 나\n- 다');

// ---- 강조글·인용 안의 줄은 안에서 ----
same('K18 강조글 본문을 목록으로 — 머리 줄과 갈리지 않음', K('> [!NOTE]\n> 첫 줄\n> 둘째 줄', 2, 3, 'bullet'), '> [!NOTE]\n> - 첫 줄\n> - 둘째 줄');
same('K19 강조글 본문 줄을 제목으로', K('> [!NOTE]\n> 첫 줄\n> 둘째 줄\n\n뒤', 3, 3, 'h3'), '> [!NOTE]\n> 첫 줄\n>\n> ### 둘째 줄\n\n뒤');
same('K20 강조글 안 목록을 문단으로 — 강조글 안에', K('> [!NOTE]\n> - 첫 줄\n> - 둘째 줄', 2, 3, 'para'), '> [!NOTE]\n> 첫 줄\n>\n> 둘째 줄');
same('K21 머리 줄부터 골라도 본문만', K('> [!NOTE]\n> 첫 줄', 1, 2, 'bullet'), '> [!NOTE]\n> - 첫 줄');
same('K22 머리 줄만 고르면 바꾸지 않음', K('> [!NOTE]\n> 첫 줄', 1, 1, 'bullet'), 'box-head');
same('K23 인용 안 목록을 문단으로 — 인용 안에', K('> - 가\n> - 나', 1, 2, 'para'), '> 가\n>\n> 나');
same('K24 인용 글을 문단으로 — 밖으로, > 빈 줄은 보통 빈 줄로', K('> 가\n>\n> 나\n>\n> 다', 3, 3, 'para'), '> 가\n\n나\n\n> 다');
same('K25 인용 두 줄을 목록으로 — 인용 안의 목록 (지금대로)', K('> 첫 줄\n> 둘째 줄', 1, 2, 'bullet'), '> - 첫 줄\n> - 둘째 줄');

// ---- 임의 시험이 찾은 것 (kinds_fuzz.js) ----
same('K25a 인용 안과 밖을 함께 고르면 바꾸지 않음', K('> 인용 줄\n\n* [ ] 항목', 1, 3, 'bullet'), 'quote-mix');
same('K25b 하위가 있는 항목을 목록으로 — 하위를 아래 목록으로 잡지 않음 (아래 * 목록에 붙는다)', K('- [ ] 가\n  - 가1\n* 나', 1, 1, 'bullet'), '* 가\n  - 가1\n* 나');
same('K25c 부모와 하위를 함께 문단으로 — 하위도 부모 수준', K('1. 가\n   - 가1\n2. 나', 1, 2, 'para'), '가\n\n가1\n\n1. 나');
same('K25d 하위·부모·하위를 제목으로 — 부모 뒤 하위는 부모 수준', K('1. 가\n   - 가1\n2. 나\n   - 나1', 2, 4, 'h3'), '1. 가\n\n   ### 가1\n\n### 나\n\n### 나1');
same('K25e 수준마다 번호 — 하위와 다음 항목을 번호로', K('1. 가\n2. 나\n   - 나1\n- 다', 3, 4, 'number'), '1. 가\n2. 나\n   1. 나1\n3. 다');
same('K25f 모두 1. 인 목록에 붙으면 1.', K('1. 가\n1. 나\n\n다', 4, 4, 'number'), '1. 가\n1. 나\n1. 다');
same('K25g 끝의 빈 줄까지 고른 인용 — 인용 밖 목록에 붙지 않음', K('> 가\n> 나\n\n1. 다\n1. 라', 1, 3, 'number'), '> 1. 가\n> 2. 나\n\n1. 다\n1. 라');
same('K25h 띄운 목록과 붙인 목록 사이 — 한 목록이 되어 띄움', K('- 가\n- 나\n\n다\n\n- 라\n\n- 마', 4, 4, 'bullet'), '- 가\n- 나\n\n- 다\n\n- 라\n\n- 마');
same('K25i 앞의 빈 줄까지 고름 — 항목 하나 목록과의 빈 줄을 지킨다', K('- 가\n\n나', 2, 3, 'bullet'), '- 가\n\n- 나');

// ---- 목록 전체를 (바꾸기 창) ----
same('K26 글머리 목록 전체를 번호로 — 하위는 따라 옮긴다', J(relist(L('- 가\n  - 가1\n- 나\n- 다'), 3, 'number')), '1. 가\n   - 가1\n2. 나\n3. 다');
same('K27 번호 목록 전체를 할 일로', J(relist(L('1. 가\n2. 나'), 1, 'task')), '- [ ] 가\n- [ ] 나');
same('K28 할 일 목록 전체를 글머리로', J(relist(L('- [x] 가\n- [ ] 나'), 2, 'bullet')), '- 가\n- 나');
same('K29 10. 이 있는 번호 목록을 글머리로 — 하위 들여쓰기', J(relist(L('9. 가\n10. 나\n    - 나1'), 2, 'bullet')), '- 가\n- 나\n  - 나1');
same('K30 목록이 아니면', J(relist(L('글'), 1, 'number')), 'not-list');

// ---- 목록 ↔ 표, 코드 ----
const H = ['항목', '내용', (k) => `열 ${k}`];
same('K31 목록을 표로 — — 로 칸을 나눈다', J(listToTable(L('앞\n\n- 가 — 1 — x\n- 나 — 2\n- 다\n\n뒤'), 3, H)),
  '앞\n\n| 항목 | 내용 | 열 3 |\n| --- | --- | --- |\n| 가 | 1 | x |\n| 나 | 2 |  |\n| 다 |  |  |\n\n뒤');
same('K32 목록을 표로 — 첫 : 로, | 는 \\|', J(listToTable(L('- 구리: 9,800달러\n- 니켈: 16,500 | 톤'), 1, H)), '| 항목 | 내용 |\n| --- | --- |\n| 구리 | 9,800달러 |\n| 니켈 | 16,500 \\| 톤 |');
same('K33 하위가 있는 목록은 표로 바꾸지 않음', J(listToTable(L('- 가\n  - 가1\n- 나'), 1, H)), 'nested-list');
same('K34 표를 목록으로 — 머리행은 빼고 빈 칸은 건너뛴다', J(tableToList(L('표 1. 가격\n\n| 품목 | 값 |\n|---|---|\n| 구리 | 9,800 |\n| 니켈 |  |\n\n뒤'), 4)),
  '표 1. 가격\n\n- 구리 — 9,800\n- 니켈\n\n뒤');
same('K35 표를 목록으로 — 캡션도 지운다', J(tableToList(L('앞\n\n표 1. 가격\n\n| 품목 | 값 |\n|---|---|\n| 구리 | 9,800 |\n\n뒤'), 6, { caption: 3 })), '앞\n\n- 구리 — 9,800\n\n뒤');
same('K36 코드로 감싸기 — 글은 표시까지 그대로', J(wrapCode(L('앞\n\n- 가\n- 나\n\n뒤'), 3, 4)), '앞\n\n```\n- 가\n- 나\n```\n\n뒤');
same('K37 코드 풀기', J(unwrapCode(L('앞\n\n```\n## 제목\n- 가\n```\n\n뒤'), 4)), '앞\n\n## 제목\n- 가\n\n뒤');
same('K38 코드 블록 안을 감싸지 않음', J(wrapCode(L('```\nx\n```'), 2, 2)), 'in-code');

// ---- 위에 넣는 새 줄은 위 블록의 양식, 아래는 그 줄의 양식 (제목 아래는 문단) ----
const N = (src, at, below) => {
  const lines = L(src);
  const plan = planNew(lines, at, below);
  if (plan.error) return plan.error;
  const r = insertLine(lines, plan, '새');
  return r.lines.join('\n');
};
same('K39 목록 뒤 문단 위 — 목록을 잇는다', N('- 가\n- 나\n\n다', 4, false), '- 가\n- 나\n- 새\n\n다');
same('K40 번호 목록 뒤 제목 위 — 다음 번호', N('1. 가\n2. 나\n\n## 2장', 4, false), '1. 가\n2. 나\n3. 새\n\n## 2장');
same('K41 강조글 뒤 제목 위 — 강조글 안', N('> [!NOTE]\n> 참고\n\n## 2장', 4, false), '> [!NOTE]\n> 참고\n>\n> 새\n\n## 2장');
same('K42 문단 뒤 제목 위 — 문단', N('앞 문단\n\n## 2장', 3, false), '앞 문단\n\n새\n\n## 2장');
same('K43 제목 아래 — 문단', N('## 1장\n\n본문', 1, true), '## 1장\n\n새\n\n본문');
same('K44 목록 첫 항목 위 — 목록 (그 줄의 양식)', N('문단\n\n- 가\n- 나', 3, false), '문단\n\n- 새\n- 가\n- 나');
same('K45 번호 항목 아래 — 다음 번호, 뒤를 다시 매김', N('1. 가\n2. 나', 1, true), '1. 가\n2. 새\n3. 나');

return { fails, n };
